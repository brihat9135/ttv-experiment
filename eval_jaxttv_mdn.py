"""
Calibration check on the jaxttv-trained MDN (mdn_jaxttv.pt), the rigorous follow-up to the
single-system agreement in retrain_compare. Uses a fresh held-out test set generated by jaxttv
(jaxttv_test.npz, seed 2, disjoint from train/val) and asks the SBI correctness question:

  Coverage:  does the X% credible interval contain the truth X% of the time, per parameter?
  SBC:       is the rank of the truth among posterior samples uniform (flat histogram)?

An amortized posterior is only trustworthy if these hold. Writes calib_jaxttv.png + json.
"""
import json, numpy as np, torch
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from model import MDN

NAMES = ["m1", "m2", "h1", "k1", "h2", "k2"]
NOISE_MIN = 0.5
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
LEVELS = [0.5, 0.68, 0.9, 0.95]

d = np.load("jaxttv_test.npz")
theta, feats = d["theta"], d["feats"]
norm = np.load("norm_jaxttv.npz")
f_mean, f_std, th_mean, th_std = norm["f_mean"], norm["f_std"], norm["th_mean"], norm["th_std"]

net = MDN(in_dim=60, theta_dim=6).to(DEVICE)
net.load_state_dict(torch.load("mdn_jaxttv.pt", map_location=DEVICE)); net.eval()

rng = np.random.default_rng(7)
obs = feats + rng.normal(0, NOISE_MIN, feats.shape)
x = torch.tensor((obs - f_mean) / f_std, dtype=torch.float32, device=DEVICE)
samp = np.empty((len(theta), 1000, 6), dtype=np.float32)
with torch.no_grad():
    for i in range(0, len(x), 1000):
        s = net.sample(x[i:i+1000], n=1000).cpu().numpy()
        samp[i:i+1000] = s * th_std + th_mean

# ---- coverage ----
print(f"Calibration of mdn_jaxttv.pt on {len(theta)} held-out jaxttv systems.\n")
print("Coverage (empirical vs nominal; ideal = nominal):")
print("  nominal | " + " | ".join(f"{n:>6}" for n in NAMES))
cov_tab = {}
for lv in LEVELS:
    lo_p, hi_p = (1 - lv) / 2 * 100, (1 + lv) / 2 * 100
    cells = []
    cov_tab[lv] = {}
    for dd in range(6):
        qlo = np.percentile(samp[:, :, dd], lo_p, axis=1)
        qhi = np.percentile(samp[:, :, dd], hi_p, axis=1)
        cov = float(np.mean((theta[:, dd] >= qlo) & (theta[:, dd] <= qhi)))
        cov_tab[lv][NAMES[dd]] = round(cov, 3); cells.append(f"{cov*100:5.1f}%")
    print(f"  {lv*100:5.0f}%  | " + " | ".join(cells))
calib_err = float(np.mean([abs(cov_tab[lv][n] - lv) for lv in LEVELS for n in NAMES]))
print(f"\n  mean |coverage - nominal| = {calib_err*100:.1f}%  (lower = better calibrated)")

# ---- SBC ranks ----
ranks = np.array([[int((samp[i, :, dd] < theta[i, dd]).sum()) for dd in range(6)]
                  for i in range(len(theta))])

# ---- figure: coverage curve + 6 SBC rank histograms ----
fig = plt.figure(figsize=(13, 8.5))
gs = fig.add_gridspec(3, 3, height_ratios=[1.3, 1, 1])
axc = fig.add_subplot(gs[0, :])
axc.plot([0, 1], [0, 1], "k--", lw=1, label="ideal")
for dd in range(6):
    axc.plot(LEVELS, [cov_tab[lv][NAMES[dd]] for lv in LEVELS], "o-", label=NAMES[dd])
axc.set_xlabel("nominal credible level"); axc.set_ylabel("empirical coverage")
axc.set_title(f"Coverage of the jaxttv-trained MDN (mean |cov-nominal| = {calib_err*100:.1f}%)")
axc.legend(fontsize=8, ncol=7, loc="lower right"); axc.grid(alpha=0.25)
for dd in range(6):
    ax = fig.add_subplot(gs[1 + dd // 3, dd % 3])
    ax.hist(ranks[:, dd], bins=20, range=(0, 1000), color="#4c72b0", alpha=0.85)
    ax.axhline(len(theta) / 20, color="k", ls="--", lw=1)
    ax.set_title(f"SBC rank: {NAMES[dd]}", fontsize=10); ax.set_yticks([])
fig.suptitle("Calibration of mdn_jaxttv.pt (flat SBC + coverage on the diagonal = calibrated)",
             fontsize=13, fontweight="bold")
fig.tight_layout(rect=[0, 0, 1, 0.97]); fig.savefig("calib_jaxttv.png", dpi=140)
print("  wrote calib_jaxttv.png")

json.dump({"n_test": len(theta), "coverage": cov_tab, "mean_calib_error": round(calib_err, 4)},
          open("_calib_jaxttv.json", "w"), indent=2)
print("  wrote _calib_jaxttv.json")
